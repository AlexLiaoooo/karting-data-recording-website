import type { MapAsset, TrackCorner, TrackLayout, TrackMapData } from "./types";

/**
 * Circuit maps that ship with the app.
 *
 * Each layout carries its own version stamp. The artwork is copied into IndexedDB the first time
 * a track uses it, so without a stamp a corrected map never reaches a device that already stored
 * the old one — and a single shared stamp would push every built-in map again whenever one of
 * them changed.
 */
export type BuiltInLayout = {
  /** Stable identity written onto the stored layout, so a renamed layout is still recognised. */
  key: string;
  name: string;
  mapUrl: string;
  version: string;
  corners: TrackCorner[];
};

export type BuiltInTrack = {
  key: string;
  name: string;
  location: string;
  notes: string;
  /**
   * Taken from the loop orientation where the source records one. Kart Silverstone has no oneway
   * tagging in OpenStreetMap, so its anti-clockwise direction comes from the owner instead — but
   * it is never guessed: a direction nobody has confirmed stays Unknown.
   */
  direction: TrackLayout["direction"];
  attribution: string;
  sourceUrl: string;
  layouts: BuiltInLayout[];
};

