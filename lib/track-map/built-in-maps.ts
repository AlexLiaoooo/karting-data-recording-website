const layoutsByKey = new Map(BUILT_IN_TRACKS.flatMap((track) => track.layouts.map((layout) => [layout.key, { track, layout }] as const)));

/**
 * Loads a map that ships with the app. Width and height come from the file's own viewBox rather
 * than being hard-coded at the call site: marker positions are stored as fractions of the asset
 * box, so a stored size that disagrees with the artwork letterboxes the image and drifts every
 * marker placed on it.
 */
export async function loadBuiltInMapAsset(url: string): Promise<MapAsset> {
  const response = await fetch(url);
  if (!response.ok) throw new Error("Built-in map unavailable.");
  const markup = await response.text();

  const viewBox = markup.match(/viewBox\s*=\s*"\s*[\d.-]+\s+[\d.-]+\s+([\d.]+)\s+([\d.]+)/);
  const width = Number(viewBox?.[1]);
  const height = Number(viewBox?.[2]);
  if (!Number.isFinite(width) || !Number.isFinite(height) || width <= 0 || height <= 0) {
    throw new Error("Built-in map has no usable viewBox.");
  }

  const blob = new Blob([markup], { type: "image/svg+xml" });
  return {
    id: crypto.randomUUID(),
    blob,
    width,
    height,
    mimeType: "image/svg+xml",
    size: blob.size,
    updatedAt: new Date().toISOString(),
  };
}

/** The fields a stored layout needs in order to carry, and later recognise, a built-in map. */
export function builtInLayoutFields(track: BuiltInTrack, layout: BuiltInLayout, asset: MapAsset) {
  return {
    mapAssetId: asset.id,
    sourceAttribution: track.attribution,
    sourceUrl: track.sourceUrl,
    builtInLayoutKey: layout.key,
    builtInMapVersion: layout.version,
    corners: layout.corners,
  };
}

/**
 * Identifies the built-in layout a stored record came from.
 *
 * The key is authoritative. Records created before keys existed have none, so PF International is
 * also matched on the track and layout names it was created with — the only built-in track that
 * could have been stored back then. That fallback is deliberately not extended to Whilton Mill:
 * no unkeyed Whilton Mill record can exist, so name-matching one could only ever capture a track
 * the user built themselves and overwrite their map.
 */
function builtInLayoutFor(data: TrackMapData, layout: TrackLayout) {
  if (layout.builtInLayoutKey) return layoutsByKey.get(layout.builtInLayoutKey);

  const track = data.tracks.find((candidate) => candidate.id === layout.trackId);
  const isLegacyPfi = track?.name.trim().toLowerCase() === "pf international" && layout.name.trim().toLowerCase() === "full layout";
  return isLegacyPfi ? layoutsByKey.get("pfi-full") : undefined;
}

/**
 * Attaches built-in maps to layouts that need one, and replaces the artwork on layouts still
 * holding an older version of it.
 *
 * A layout whose map the user replaced has no `sourceAttribution` (uploadImage clears it), which
 * is what marks it as user-owned and off-limits here. Returns the input unchanged when there is
 * nothing to do, so callers can assign the result unconditionally.
 */
export async function refreshBuiltInMaps(data: TrackMapData): Promise<TrackMapData> {
  const stale = data.layouts
    .map((layout) => ({ layout, builtIn: builtInLayoutFor(data, layout) }))
    .filter((entry): entry is { layout: TrackLayout; builtIn: NonNullable<ReturnType<typeof builtInLayoutFor>> } => {
      if (!entry.builtIn) return false;
      const carriesBuiltInMap = !entry.layout.mapAssetId || Boolean(entry.layout.sourceAttribution);
      return carriesBuiltInMap && entry.layout.builtInMapVersion !== entry.builtIn.layout.version;
    });
  if (!stale.length) return data;

  // One fetch per distinct map, however many layouts are waiting on it.
  const urls = [...new Set(stale.map((entry) => entry.builtIn.layout.mapUrl))];
  const assets = new Map(await Promise.all(urls.map(async (url) => [url, await loadBuiltInMapAsset(url)] as const)));

  const fieldsByLayoutId = new Map(stale.map((entry) => [
    entry.layout.id,
    {
      ...builtInLayoutFields(entry.builtIn.track, entry.builtIn.layout, assets.get(entry.builtIn.layout.mapUrl)!),
      // Fills a direction that was never chosen — records created before the registry knew one
      // were all stamped Unknown. A direction the user picked is left alone.
      ...(entry.layout.direction === "Unknown" ? { direction: entry.builtIn.track.direction } : {}),
    },
  ]));
  const replacedAssetIds = new Set(stale.map((entry) => entry.layout.mapAssetId).filter((id): id is string => Boolean(id)));
  const timestamp = new Date().toISOString();

  return {
    ...data,
    assets: [...data.assets.filter((candidate) => !replacedAssetIds.has(candidate.id)), ...assets.values()],
    layouts: data.layouts.map((layout) => {
      const fields = fieldsByLayoutId.get(layout.id);
      return fields ? { ...layout, ...fields, updatedAt: timestamp } : layout;
    }),
  };
}

/**
 * Builds the Track and Layout records for a built-in circuit, ready to append to the store.
 *
 * A map that fails to load is not fatal: the track is still created without one, and
 * refreshBuiltInMaps attaches the artwork on a later load once the file is reachable.
 */
export async function createBuiltInTrack(track: BuiltInTrack, timestamp: string) {
  const trackId = crypto.randomUUID();
  const assets: MapAsset[] = [];

  const layouts = await Promise.all(track.layouts.map(async (layout) => {
    let asset: MapAsset | undefined;
    try {
      asset = await loadBuiltInMapAsset(layout.mapUrl);
      assets.push(asset);
    } catch {
      // Leave the layout without a map; the user can upload one or reload to pick it up.
    }
    return {
      id: crypto.randomUUID(),
      trackId,
      name: layout.name,
      direction: track.direction,
      // The key and corners are stored either way, so a layout whose artwork failed to load is
      // still recognised as built-in and picks the map up on a later load.
      ...(asset
        ? builtInLayoutFields(track, layout, asset)
        : { mapAssetId: null, builtInLayoutKey: layout.key, corners: layout.corners }),
      markers: [],
      createdAt: timestamp,
      updatedAt: timestamp,
    } satisfies TrackLayout;
  }));

  return {
    track: { id: trackId, name: track.name, location: track.location, notes: track.notes, createdAt: timestamp, updatedAt: timestamp },
    layouts,
    assets,
    mapsLoaded: assets.length,
  };
}
